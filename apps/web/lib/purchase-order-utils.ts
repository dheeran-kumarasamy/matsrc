import { PurchaseOrderStatus, calculateLineGst } from "@matsrc/db";

export function toNumber(value: unknown): number {
  return value === null || value === undefined ? 0 : Number(value);
}

// Verify and Fix PO Generation to Use Accepted Supplier RFQ Price.
//
// Builds a single PurchaseOrderLineItem.create payload from a confirmed
// OrderItem. `item.unitPrice` is read as-is — it is ALREADY the accepted
// supplier RFQ quotation price (overwritten from the winning
// SupplierQuote.unitPrice by BestPriceSelectionService.
// selectAndFinalizeIfEligible at quote-acceptance time — see
// apps/api/src/supplier/rfqs/best-price-selection.service.ts). This
// function never reads Product.basePrice/PricingTier, so a later catalogue
// price change can never leak into a PO.
//
// `tax` is computed via the same shared calculateLineGst used by the RFQ
// quotation flow, from this same accepted unitPrice and the OrderItem's own
// taxRatePercent (falls back to DEFAULT_TAX_RATE_PERCENT when absent —
// never hard-coded to a single rate for every product).
export function buildPurchaseOrderLineItemData(item: {
  productId: string;
  quantity: number;
  unitPrice: unknown;
  taxRatePercent?: unknown;
  deliveryDate?: Date | null;
}, fallbackDeliveryDate: Date | null) {
  const gst = calculateLineGst({
    quantity: item.quantity,
    unitPrice: toNumber(item.unitPrice),
    gstRatePercent:
      item.taxRatePercent !== null && item.taxRatePercent !== undefined ? toNumber(item.taxRatePercent) : null,
  });

  return {
    productId: item.productId,
    quantity: item.quantity,
    unitPrice: gst.unitPrice,
    tax: gst.gstAmount,
    // Persist the RATE alongside the computed amount — previously only
    // `tax` (the amount) was stored, so the PO PDF/UI could never show an
    // explicit "GST @ 18%" breakdown, only a silent lump-sum figure.
    // gst.gstRatePercent is always a resolved number here (never null —
    // calculateLineGst() already applies DEFAULT_TAX_RATE_PERCENT when the
    // input omitted it), so this is never left unset for a newly created
    // line item.
    taxRatePercent: gst.gstRatePercent,
    deliveryDate: item.deliveryDate ?? fallbackDeliveryDate ?? null,
  };
}

export async function generatePoNumber(prisma: any): Promise<string> {
  const year = new Date().getFullYear();
  const count = await prisma.purchaseOrder.count({
    where: {
      createdAt: {
        gte: new Date(`${year}-01-01T00:00:00.000Z`),
        lt: new Date(`${year + 1}-01-01T00:00:00.000Z`),
      },
    },
  });
  const sequence = String(count + 1).padStart(5, "0");
  return `PO-${year}-${sequence}`;
}

// Buyer Portal PO Display / Downloaded PDF Number mismatch fix.
//
// The buyer portal's PO list/detail pages were displaying
// `PurchaseOrder.poNumber` (e.g. "PO-2026-00001", generated by
// generatePoNumber() above) — a separate, legacy document-number series
// — while the downloaded buyer-facing PDF (see
// app/api/builder/purchase-orders/[id]/export/route.ts and
// lib/purchase-order-pdf.ts's resolvePoDocumentView, both already fixed by
// the earlier Buyer-Facing/Supplier-Facing PO Identity task) prints and
// names the file after the Order's own, already-authoritative
// `orderNumber` (format "OD/YYMM/SSSSS" — see
// packages/db/lib/business-number.ts), falling back to `poNumber` only
// for pre-payment-approval orders that have not yet been assigned one.
// This is the SAME fallback the PDF route already uses for both its
// filename and its printed document number — the two were already
// consistent with EACH OTHER, just not with the portal UI, which this
// fixes by reusing the identical expression rather than inventing a new
// convention, a new field, or regenerating/altering any stored number.
export function resolveBuyerPoDocumentNumber(po: { orderNumber?: string | null; poNumber: string }): string {
  return po.orderNumber ?? po.poNumber;
}

export function serializePurchaseOrder(po: any) {
  return {
    id: po.id,
    poNumber: po.poNumber,
    status: po.status,
    version: po.version,
    notes: po.notes,
    termsSnapshot: po.termsSnapshot,
    approvedAt: po.approvedAt,
    approvedBy: po.approvedBy,
    createdAt: po.createdAt,
    updatedAt: po.updatedAt,
    orderId: po.orderId,
    // Meaningful Enquiry ID (e.g. "ABC-SITE01-000123") — only present when
    // the caller's query included the `order` relation (see
    // `purchaseOrderInclude` below). See packages/db/lib/enquiry-id.ts.
    enquiryId: po.order?.enquiryId ?? po.orderId,
    orderNumber: po.order?.orderNumber ?? null,
    // Underlying Order.status (PLACED/PROCESSING/.../CANCELLED) — surfaced so
    // the PO screen can offer "Cancel Order" only when the order is still in
    // a builder-cancellable state, without a second round-trip. Only present
    // when the caller's query included the `order` relation.
    orderStatus: po.order?.status ?? null,
    // The order's tagged construction Site (nullable — "Unassigned" is
    // valid). Surfaced ONLY so the PO screen's "Create New Enquiry" action
    // can carry the same site forward into a fresh /sourcing session as a
    // convenience — it is never written back to this PO, and the sourcing
    // flow still fully re-validates ownership/ACTIVE status server-side
    // before ever persisting it (see session-store.ts's createSession).
    orderSiteId: po.order?.siteId ?? null,
    supplier: {
      id: po.supplier.id,
      companyName: po.supplier.companyName,
      gstin: po.supplier.gstin ?? null,
      region: po.supplier.region ?? null,
      email: po.supplier.user?.email ?? null,
      phone: po.supplier.user?.phone ?? null,
    },
    builder: {
      id: po.builder.id,
      name: po.builder.name,
      email: po.builder.email,
      phone: po.builder.phone ?? null,
    },
    // The order's delivery/"ship to" destination — the Purchase Order PDF
    // (see app/api/builder/purchase-orders/[id]/export/route.ts) displays
    // this as a DELIVER TO section that is always kept separate from the
    // BUYER DETAILS (BuildOhub) section, even though BuildOhub is the
    // buyer: the delivery recipient is legitimately the builder's own
    // construction site, never the purchasing party. Falls back to the
    // order's free-text deliveryAddress when no Site is tagged. Only
    // present when the caller's query included the `order` relation with
    // `site` selected (see `purchaseOrderInclude` below).
    deliverTo: po.order?.site
      ? {
          name: po.order.site.name,
          addressLine: po.order.site.addressLine ?? null,
          city: po.order.site.city ?? null,
          state: po.order.site.state ?? null,
          pincode: po.order.site.pincode ?? null,
          gstin: po.order.site.gstin ?? null,
        }
      : po.order?.deliveryAddress
        ? { name: null, addressLine: po.order.deliveryAddress, city: null, state: null, pincode: null, gstin: null }
        : null,
    lineItems: po.lineItems.map((li: any) => ({
      id: li.id,
      productId: li.productId,
      productName: li.product.name,
      unit: li.product.unit,
      quantity: li.quantity,
      unitPrice: toNumber(li.unitPrice),
      tax: toNumber(li.tax),
      // The GST rate (percentage) used to compute `tax` above — null only
      // for pre-migration line items created before this column existed
      // (see PurchaseOrderLineItem's doc comment in schema.prisma); the
      // PDF/UI must show a generic "Tax" label for those rather than
      // fabricating a rate.
      taxRatePercent: li.taxRatePercent !== null && li.taxRatePercent !== undefined ? toNumber(li.taxRatePercent) : null,
      deliveryDate: li.deliveryDate,
      fulfilledQuantity: li.fulfilledQuantity,
      lineTotal: toNumber(li.unitPrice) * li.quantity + toNumber(li.tax),
    })),
    // Explicit subtotal/GST/grand-total breakdown — mirrors the Invoice's
    // own subtotal/taxAmount/totalAmount fields so the PO PDF/UI can show
    // the same "Subtotal + GST = Total" structure instead of folding tax
    // silently into a single TOTAL figure.
    subtotal: po.lineItems.reduce((acc: number, li: any) => acc + toNumber(li.unitPrice) * li.quantity, 0),
    taxAmount: po.lineItems.reduce((acc: number, li: any) => acc + toNumber(li.tax), 0),
    total: po.lineItems.reduce(
      (acc: number, li: any) => acc + toNumber(li.unitPrice) * li.quantity + toNumber(li.tax),
      0
    ),
    exportUrl: `/api/builder/purchase-orders/${po.id}/export`,
  };
}

